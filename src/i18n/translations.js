/**
 * Deep Fallback Proxy for Safe Translation Retrieval
 * Ensures every section, subsection, and nested key falls back recursively to English
 * rather than throwing undefined or breaking the UI.
 * Also handles aliasing bridges (gallery -> memory, wellness -> progress, guardian -> caregiver).
 */
export function getTranslationProxy(lang = 'en') {
  const primary = translations[lang] || translations.en;
  const fallback = translations.en;

  function createDeepProxy(targetObj, fallbackObj) {
    const safeTarget = targetObj || {};
    const safeFallback = fallbackObj || {};

    return new Proxy(safeTarget, {
      get(target, prop) {
        if (typeof prop === 'symbol') return target[prop];

        // Semantic Aliasing Bridges:
        if (prop === 'gallery') {
          const actual = target.gallery || target.memory;
          const fb = safeFallback.gallery || safeFallback.memory;
          return createDeepProxy(actual, fb);
        }
        if (prop === 'wellness') {
          const actual = target.wellness || target.progress;
          const fb = safeFallback.wellness || safeFallback.progress;
          return createDeepProxy(actual, fb);
        }
        if (prop === 'guardian') {
          const actual = target.guardian || target.caregiver;
          const fb = safeFallback.guardian || safeFallback.caregiver;
          return createDeepProxy(actual, fb);
        }

        const value = target[prop];
        const fbValue = safeFallback[prop];

        // If target has property
        if (value !== undefined && value !== null) {
          if (typeof value === 'object' && !Array.isArray(value)) {
            return createDeepProxy(value, fbValue && typeof fbValue === 'object' ? fbValue : {});
          }
          return value;
        }

        // If fallback has property
        if (fbValue !== undefined && fbValue !== null) {
          if (typeof fbValue === 'object' && !Array.isArray(fbValue)) {
            return createDeepProxy({}, fbValue);
          }
          return fbValue;
        }

        return '';
      }
    });
  }

  return createDeepProxy(primary, fallback);
}

// Backward compatibility helper
export function getTranslation(lang = 'en') {
  return getTranslationProxy(lang);
}
